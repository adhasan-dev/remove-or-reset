class DataRoot:
    def __init__(self, path):
        self.root = Path(path).resolve(strict=True)
        self._fingerprint = sha256(self.root / "manifest.json")
        self.manifest = read_json(self.root / "manifest.json")
        if self.manifest.get("format") != "remove-reset-data-v1" or not isinstance(
            self.manifest.get("files"), dict
        ):
            raise ValueError("Expected remove-reset-data-v1 manifest and files mapping")
        self.verified = {}
        for name in self.manifest["files"]:
            local_path(self.root, name)

    @property
    def fingerprint(self):
        if sha256(self.root / "manifest.json") != self._fingerprint:
            raise ValueError("Data manifest changed during this invocation")
        return self._fingerprint

    def path(self, name):
        if name not in self.manifest["files"]:
            raise ValueError(f"Undeclared data file: {name}")
        self.verify(name)
        return local_path(self.root, name)

    def verify(self, name):
        if name in self.verified:
            return self.verified[name]
        path = local_path(self.root, name)
        binding = self.manifest["files"][name]
        if not isinstance(binding, dict):
            raise ValueError(f"Invalid data binding: {name}")
        if not path.is_file() or sha256(path) != digest(binding.get("sha256")):
            raise ValueError(f"Missing or changed data file: {name}")
        result = {"sha256": binding["sha256"], "bytes": path.stat().st_size}
        if path.suffix == ".gz":
            uncompressed = hashlib.sha256()
            count = 0
            size = 0
            with gzip.open(path, "rb") as stream:
                for line in stream:
                    uncompressed.update(line)
                    size += len(line)
                    count += bool(line.strip())
            expected = binding.get("uncompressed_sha256")
            if expected is None or uncompressed.hexdigest() != digest(expected):
                raise ValueError(f"Uncompressed checksum mismatch: {name}")
            result.update(uncompressed_sha256=uncompressed.hexdigest(), uncompressed_bytes=size)
            if ".jsonl" in path.name and binding.get("records") != count:
                raise ValueError(f"Declared JSONL row count mismatch: {name}")
        elif "records" in binding and ".jsonl" in path.name:
            if len(read_jsonl(path)) != binding["records"]:
                raise ValueError(f"Declared JSONL row count mismatch: {name}")
        self.verified[name] = result
        return result

    def rows(self, name):
        rows = read_jsonl(self.path(name))
        if any(not isinstance(row, dict) for row in rows):
            raise ValueError(f"Every JSONL record must be an object: {name}")
        return rows

    def split(self, name):
        if name not in SPLITS:
            raise ValueError(f"Unknown SQL split: {name}")
        relative = f"sql/{name}.jsonl.gz"
        rows = self.rows(relative)
        if len(rows) != SPLITS[name]:
            raise ValueError(f"Frozen {name} row count differs")
        validate_records(rows)
        if name == "train" and self.verified[relative]["uncompressed_sha256"] != TRAIN_SHA256:
            raise ValueError("Frozen training byte identity differs")
        return rows

    def check(self):
        return {name: self.verify(name) for name in sorted(self.manifest["files"])}


def validate_records(rows, *, id_key="id", require_target=True):
    ids = []
    for row in rows:
        if not isinstance(row.get(id_key), str) or not row[id_key]:
            raise ValueError(f"Every record needs a nonempty {id_key}")
        ids.append(row[id_key])
        if not isinstance(row.get("input"), str) or not row["input"].strip():
            raise ValueError("Record input must be nonempty text")
        if "\x00" in row["input"]:
            raise ValueError("NUL in model input")
        if require_target and not isinstance(row.get("target"), str):
            raise ValueError("Record target must be explicit text")
    if len(set(ids)) != len(ids):
        raise ValueError("Duplicate record IDs")


@dataclass
class EncodedRecord:
    input_ids: list[int]
    labels: list[int]
    prompt_length: int
    target_tokens: int
    eligible: bool = True
    reason: str | None = None

    def validate(self, *, vocab_size=None):
        if (
            not self.eligible
            or self.reason is not None
            or type(self.prompt_length) is not int
            or not 1 <= self.prompt_length < len(self.input_ids)
            or type(self.target_tokens) is not int
            or self.target_tokens != len(self.input_ids) - self.prompt_length
            or self.labels != [-100] * self.prompt_length + self.input_ids[self.prompt_length :]
        ):
            raise ValueError("Invalid complete causal record/target mask")
        if any(
            type(x) is not int or x < 0 or (vocab_size is not None and x >= vocab_size)
            for x in self.input_ids
        ):
            raise ValueError("Token IDs must be in the actual vocabulary")
        return self


def encode_record(tokenizer, row, max_length=2048):
    """BOS + separately encoded prompt; target = encode('\\n'+target) + EOS.

    Prompt and padding are -100. Target labels remain at their ORIGINAL input
    positions; target_loss explicitly requests the PREVIOUS causal positions.
    Never merge strings across the prompt boundary, pack, or truncate.
    """
    if type(max_length) is not int or max_length < 1:
        raise ValueError("max_length must be a positive integer")
    if not isinstance(row.get("input"), str) or not isinstance(row.get("target"), str):
        raise ValueError("Encoding requires explicit input and target strings")
    if tokenizer.bos_token_id is None or tokenizer.eos_token_id is None:
        raise ValueError("Tokenizer must define BOS and EOS")
    prompt = [tokenizer.bos_token_id] + list(
        tokenizer.encode(row["input"], add_special_tokens=False)
    )
    target = list(tokenizer.encode("\n" + row["target"], add_special_tokens=False))
    target.append(tokenizer.eos_token_id)
    ids = prompt + target
    record = EncodedRecord(
        ids,
        [-100] * len(prompt) + target,
        len(prompt),
        len(target),
        len(ids) <= max_length,
        None if len(ids) <= max_length else "context_length",
    )
    if record.eligible:
        record.validate()
    return record


def training_order(count, seed=42, *, study=True):
    if type(seed) is not int or not 0 <= seed < 2**32:
        raise ValueError("Training seed must be a nonnegative 32-bit integer")
    order = list(range(count))
    random.Random(seed).shuffle(order)
    if study and (
        count != 62817 or (seed == 42 and value_hash(order) != ORDER_SHA256)
    ):
        raise ValueError("Full frozen training order differs")
    return order


def tokenizer_signature(tokenizer):
    """Exact source token_cache signature, including the fast-tokenizer backend.

    The historical helper uses JSON's ASCII escaping, unlike canonical_bytes.
    Preserve that distinction so frozen calibration signatures really verify.
    Tokenizer file hashes are additionally bound by the offline model loader.
    """
    value = {
        "class": type(tokenizer).__name__,
        "vocab": tokenizer.get_vocab(),
        "special_tokens": {key: str(item) for key, item in tokenizer.special_tokens_map.items()},
        "bos": tokenizer.bos_token_id,
        "eos": tokenizer.eos_token_id,
        "pad": tokenizer.pad_token_id,
    }
    if getattr(tokenizer, "backend_tokenizer", None):
        value["backend"] = tokenizer.backend_tokenizer.to_str()
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    ).hexdigest()


def training_tokens(data, tokenizer, workspace):
    """Build/reuse reader-local token IDs, bound to data, tokenizer AND serializer."""
    name = "sql/train.jsonl.gz"
    data.path(name)
    identity = {
        "format": "remove-reset-token-cache-v1",
        "data_manifest": data.fingerprint,
        "dataset": data.verified[name],
        "tokenizer": tokenizer_signature(tokenizer),
        "serializer_source": sha256(__file__),
        "max_length": 2048,
    }
    directory = Path(workspace) / "tokens" / value_hash(identity)
    path = directory / "records.jsonl.gz"
    if directory.exists():
        metadata = read_json(directory / "metadata.json")
        if metadata["identity"] != identity or sha256(path) != metadata["sha256"]:
            raise ValueError("Reader token cache identity/checksum changed")
        entries = read_jsonl(path)
        records = [
            EncodedRecord(
                e["input_ids"],
                [-100] * e["prompt_length"] + e["input_ids"][e["prompt_length"] :],
                e["prompt_length"],
                len(e["input_ids"]) - e["prompt_length"],
            ).validate()
            for e in entries
        ]
        ids = [e["id"] for e in entries]
    else:
        rows = data.split("train")
        records = [encode_record(tokenizer, row).validate() for row in rows]
        ids = [row["id"] for row in rows]
        directory.mkdir(parents=True, exist_ok=False)
        with (
            path.open("xb") as raw,
            gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as zipped,
        ):
            for row, record in zip(rows, records, strict=True):
                zipped.write(
                    canonical_bytes(
                        {
                            "id": row["id"],
                            "input_ids": record.input_ids,
                            "prompt_length": record.prompt_length,
                        }
                    )
                    + b"\n"
                )
        write_json(
            directory / "metadata.json",
            {"identity": identity, "sha256": sha256(path), "ids_sha256": value_hash(ids)},
        )
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate training token-cache IDs")
    summary = {
        "examples": len(records),
        "nonpadding_tokens": sum(len(r.input_ids) for r in records),
        "target_tokens": sum(r.target_tokens for r in records),
        "ids_sha256": value_hash(ids),
        "cache_sha256": sha256(path),
        "identity": identity,
        "packing": False,
        "truncation": False,
    }
    if (summary["examples"], summary["nonpadding_tokens"], summary["target_tokens"]) != (
        62817,
        7628998,
        2087265,
    ):
        raise ValueError("Frozen training examples/token accounting differs")
    if len(records[training_order(len(records))[-1]].input_ids) < 1:
        raise ValueError("Empty final training example")
    if records[training_order(len(records))[-1]].target_tokens != 19:
        raise ValueError("Frozen one-example final update must contain 19 target tokens")
    return records, summary


def evaluation_panels(data, database_root=None):
    doc = read_json(data.path("sql/evaluation_panels.json"))
    if doc.get("format") != "remove-reset-evaluation-panels-v1" or doc.get("seed") != 20261013:
        raise ValueError("Unsupported evaluation panels")
    for key, count in (("sql", 128), ("validation", 256), ("reasoning", 128)):
        if len(doc[key]) != count:
            raise ValueError(f"Frozen evaluation denominator differs: {key}")
        validate_records(doc[key])
    if (
        value_hash(sorted(r["id"] for r in doc["sql"])) != SQL_ID_SHA256
        or value_hash(sorted(r["id"] for r in doc["validation"])) != VALIDATION_ID_SHA256
        or value_hash(doc["reasoning"]) != REASONING_SHA256
    ):
        raise ValueError("Frozen evaluation ID/record identity differs")
    if Counter(r["task"] for r in doc["reasoning"]) != {"direct": 64, "two_step": 64}:
        raise ValueError("Reasoning task denominator differs")
    if len(doc["databases"]) != 20:
        raise ValueError("Exactly 20 frozen SQL databases are required")
    databases = {}
    for key, binding in doc["databases"].items():
        if database_root is None:
            path = local_path(data.root, binding["path"])
        else:
            # External materialization keeps the same db_id/db_id.sqlite layout.
            path = local_path(database_root, f"{key}/{key}.sqlite")
        if not path.is_file() or sha256(path) != digest(binding["sha256"]):
            raise ValueError(
                f"Missing/changed database {key}; materialize the pinned upstream file"
            )
        databases[key] = {**binding, "path": str(path.resolve())}
    return {**doc, "databases": databases}


def materialize_databases(data, archive, output):
    """Explicit local-archive operation; no network, general unzip, or bundled DBs.

    The release must declare the archive hash and exact member name for each
    licensed upstream database. The reader obtains the archive independently.
    Only the selected, hash-matched members are written to reader-owned output.
    """
    doc = read_json(data.path("sql/evaluation_panels.json"))
    binding = doc.get("database_archive", {})
    if sha256(archive) != digest(binding.get("sha256"), "upstream database archive hash"):
        raise ValueError("Upstream database archive checksum mismatch")
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    with zipfile.ZipFile(archive) as zipped:
        for key, item in doc["databases"].items():
            target = local_path(output, f"{key}/{key}.sqlite")
            member = item.get("archive_member")
            if not isinstance(member, str) or member not in zipped.namelist():
                raise ValueError(f"Missing explicitly declared archive member: {key}")
            target.parent.mkdir(parents=True, exist_ok=True)
            with zipped.open(member) as incoming, target.open("xb") as outgoing:
                while block := incoming.read(1024 * 1024):
                    outgoing.write(block)
            if sha256(target) != digest(item["sha256"]):
                raise ValueError(f"Extracted database checksum mismatch: {key}")
            target.chmod(0o444)
    return {"databases": len(doc["databases"]), "archive_sha256": sha256(archive)}
